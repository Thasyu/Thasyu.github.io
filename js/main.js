  function getTip(tipsArray) {
    return tipsArray[dayIndex % tipsArray.length];
  }

  function getTop3(tipsArray) {
    const startIndex = dayIndex % tipsArray.length;
    return [
      tipsArray[startIndex % tipsArray.length],
      tipsArray[(startIndex + 1) % tipsArray.length],
      tipsArray[(startIndex + 2) % tipsArray.length]
    ];
  }

