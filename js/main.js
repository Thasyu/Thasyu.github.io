  // ====== スライド更新 ======
  function updateSlides() {
    slides.forEach((s, i) => s.classList.toggle("active", i === current));
    track.style.transform = `translateX(-${current * 100}%)`;
    dots.forEach((d, i) => d.classList.toggle("active", i === current));
  }

  // ====== 移動 ======
  function nextSlide() {
    if (isAnimating) return;
    isAnimating = true;
    current = (current + 1) % slides.length;
    updateSlides();
    setTimeout(() => { isAnimating = false; }, 500);
  }

  function prevSlide() {
    if (isAnimating) return;
    isAnimating = true;
    current = (current - 1 + slides.length) % slides.length;
    updateSlides();
    setTimeout(() => { isAnimating = false; }, 500);
  }

  function goToSlide(idx) {
    current = idx % slides.length;
    updateSlides();
  }

  // ====== 自動スライド ======
  function startAutoSlide() {
    stopAutoSlide();
    autoSlideTimer = setInterval(() => {
      if (!isHovering) nextSlide();
    }, autoSlideInterval);
  }

  function stopAutoSlide() {
    if (autoSlideTimer) clearInterval(autoSlideTimer);
  }

  function resetAutoSlide() {
    stopAutoSlide();
    startAutoSlide();
  }

  // ====== ボタン ======
  prevBtn && prevBtn.addEventListener("click", () => { prevSlide(); resetAutoSlide(); });
  nextBtn && nextBtn.addEventListener("click", () => { nextSlide(); resetAutoSlide(); });

  // ====== ホバーで停止 ======
  const container = document.getElementById("carousel-root") || document.querySelector(".carousel-wrapper");
  if (container) {
    container.addEventListener("mouseenter", () => { isHovering = true; });
    container.addEventListener("mouseleave", () => { isHovering = false; });
  }

  // ====== スワイプ対応 ======
  let touchStartX = 0;
  track.addEventListener("touchstart", (e) => { touchStartX = e.changedTouches[0].clientX; }, {passive:true});
  track.addEventListener("touchend", (e) => {
    const dx = e.changedTouches[0].clientX - touchStartX;
    if (Math.abs(dx) > 40) {
      if (dx < 0) nextSlide();
      else prevSlide();
      resetAutoSlide();
    }
  });

  // ====== キーボード対応 ======
  document.addEventListener("keydown", (e) => {
    if (e.key === "ArrowLeft") { prevSlide(); resetAutoSlide(); }
    if (e.key === "ArrowRight") { nextSlide(); resetAutoSlide(); }
  });

  // ====== 初期表示 ======
  updateSlides();
  startAutoSlide();
